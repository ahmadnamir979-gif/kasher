"""Iteration 4 backend tests: auto barcode on product create, held invoices, stock transfers."""
import os
import uuid
import pytest
import requests
from pathlib import Path

BASE_URL = os.environ.get('REACT_APP_BACKEND_URL')
if not BASE_URL:
    for line in Path('/app/frontend/.env').read_text().splitlines():
        if line.startswith('REACT_APP_BACKEND_URL='):
            BASE_URL = line.split('=', 1)[1].strip()
BASE_URL = BASE_URL.rstrip('/')

ADMIN_EMAIL = "admin@pos.com"
ADMIN_PASS = "Admin@1234"


def H(t): return {"Authorization": f"Bearer {t}"}


@pytest.fixture(scope="module")
def admin_token():
    r = requests.post(f"{BASE_URL}/api/auth/login", json={"email": ADMIN_EMAIL, "password": ADMIN_PASS})
    assert r.status_code == 200, r.text
    return r.json()["token"]


@pytest.fixture(scope="module")
def shop_owner(admin_token):
    tag = uuid.uuid4().hex[:8]
    email = f"TEST_it4_{tag}@pos.com"
    pw = "Owner@1234"
    r = requests.post(f"{BASE_URL}/api/admin/shops", headers=H(admin_token), json={
        "name": f"TEST_it4_shop_{tag}", "owner_email": email, "owner_name": "Owner it4",
        "owner_password": pw, "phone": "", "address": "", "subscription_months": 12
    })
    assert r.status_code == 200, r.text
    r2 = requests.post(f"{BASE_URL}/api/auth/login", json={"email": email, "password": pw})
    assert r2.status_code == 200
    return {"token": r2.json()["token"], "shop_id": r.json()["shop_id"], "email": email}


# -------------------- Auto barcode --------------------
class TestAutoBarcode:
    def test_missing_barcode_autogenerated(self, shop_owner):
        r = requests.post(f"{BASE_URL}/api/products", headers=H(shop_owner["token"]),
                          json={"name": "TEST_bc_auto", "sale_price": 5, "cost_price": 2, "stock": 10})
        assert r.status_code == 200, r.text
        p = r.json()
        assert isinstance(p.get("barcode"), str)
        assert len(p["barcode"]) == 13, f"expected 13 digits got {p['barcode']}"
        assert p["barcode"].startswith("2")
        assert p["barcode"].isdigit()

    def test_empty_barcode_string_autogenerated(self, shop_owner):
        r = requests.post(f"{BASE_URL}/api/products", headers=H(shop_owner["token"]),
                          json={"name": "TEST_bc_empty", "barcode": "", "sale_price": 5, "cost_price": 2, "stock": 10})
        assert r.status_code == 200
        p = r.json()
        assert len(p["barcode"]) == 13 and p["barcode"].startswith("2")

    def test_provided_barcode_preserved(self, shop_owner):
        r = requests.post(f"{BASE_URL}/api/products", headers=H(shop_owner["token"]),
                          json={"name": "TEST_bc_provided", "barcode": "1234567890123",
                                "sale_price": 5, "cost_price": 2, "stock": 10})
        assert r.status_code == 200
        assert r.json()["barcode"] == "1234567890123"


# -------------------- Held Invoices --------------------
class TestHeldInvoices:
    def test_empty_items_400(self, shop_owner):
        r = requests.post(f"{BASE_URL}/api/held-invoices", headers=H(shop_owner["token"]),
                          json={"items": [], "discount": 0})
        assert r.status_code == 400

    def test_create_list_delete_held(self, shop_owner):
        # need a product
        rp = requests.post(f"{BASE_URL}/api/products", headers=H(shop_owner["token"]),
                           json={"name": "TEST_held_prod", "sale_price": 10, "cost_price": 4, "stock": 20})
        p = rp.json()
        payload = {
            "label": "TEST_park1",
            "customer_name": "زبون تجريبي",
            "items": [{"product_id": p["id"], "name": p["name"], "qty": 2, "price": 10, "cost": 4}],
            "discount": 0, "notes": "test"
        }
        r = requests.post(f"{BASE_URL}/api/held-invoices", headers=H(shop_owner["token"]), json=payload)
        assert r.status_code == 200, r.text
        h = r.json()
        assert h["label"] == "TEST_park1"
        assert len(h["items"]) == 1
        hid = h["id"]

        # list
        rl = requests.get(f"{BASE_URL}/api/held-invoices", headers=H(shop_owner["token"]))
        assert rl.status_code == 200
        ids = [x["id"] for x in rl.json()]
        assert hid in ids

        # delete
        rd = requests.delete(f"{BASE_URL}/api/held-invoices/{hid}", headers=H(shop_owner["token"]))
        assert rd.status_code == 200

        rl2 = requests.get(f"{BASE_URL}/api/held-invoices", headers=H(shop_owner["token"]))
        assert hid not in [x["id"] for x in rl2.json()]

    def test_held_scoped_to_shop(self, shop_owner, admin_token):
        # create a second shop, ensure lists are isolated
        tag = uuid.uuid4().hex[:8]
        email = f"TEST_it4b_{tag}@pos.com"
        pw = "Owner@1234"
        requests.post(f"{BASE_URL}/api/admin/shops", headers=H(admin_token), json={
            "name": f"TEST_it4_shopB_{tag}", "owner_email": email, "owner_name": "Owner B",
            "owner_password": pw, "phone": "", "address": "", "subscription_months": 12
        })
        tokB = requests.post(f"{BASE_URL}/api/auth/login", json={"email": email, "password": pw}).json()["token"]
        rp = requests.post(f"{BASE_URL}/api/products", headers=H(tokB),
                           json={"name": "TEST_B_prod", "sale_price": 3, "cost_price": 1, "stock": 5})
        pB = rp.json()
        requests.post(f"{BASE_URL}/api/held-invoices", headers=H(tokB), json={
            "label": "TEST_parkB",
            "items": [{"product_id": pB["id"], "name": pB["name"], "qty": 1, "price": 3, "cost": 1}],
            "discount": 0
        })
        # owner A must not see B's held
        rl = requests.get(f"{BASE_URL}/api/held-invoices", headers=H(shop_owner["token"]))
        labels = [x["label"] for x in rl.json()]
        assert "TEST_parkB" not in labels


# -------------------- Stock Transfers --------------------
class TestTransfers:
    @pytest.fixture(scope="class")
    def owner(self, admin_token):
        # fresh shop for transfers
        tag = uuid.uuid4().hex[:8]
        email = f"TEST_it4t_{tag}@pos.com"
        pw = "Owner@1234"
        requests.post(f"{BASE_URL}/api/admin/shops", headers=H(admin_token), json={
            "name": f"TEST_it4_shopT_{tag}", "owner_email": email, "owner_name": "Owner T",
            "owner_password": pw, "phone": "", "address": "", "subscription_months": 12
        })
        tok = requests.post(f"{BASE_URL}/api/auth/login", json={"email": email, "password": pw}).json()["token"]
        return {"token": tok, "email": email}

    def test_empty_transfers_list_on_fresh_shop(self, owner):
        r = requests.get(f"{BASE_URL}/api/transfers", headers=H(owner["token"]))
        assert r.status_code == 200
        assert r.json() == []

    def test_from_equals_to_400(self, owner):
        rw = requests.get(f"{BASE_URL}/api/warehouses", headers=H(owner["token"]))
        default_w = next(w for w in rw.json() if w.get("is_default"))
        r = requests.post(f"{BASE_URL}/api/transfers", headers=H(owner["token"]), json={
            "from_warehouse_id": default_w["id"],
            "to_warehouse_id": default_w["id"],
            "items": [{"product_id": "x", "name": "y", "qty": 1}]
        })
        assert r.status_code == 400
        assert "متطابقان" in r.text

    def test_product_not_in_from_warehouse_400(self, owner):
        # create an extra warehouse WH2
        rw = requests.post(f"{BASE_URL}/api/warehouses", headers=H(owner["token"]),
                           json={"name": "TEST_WH2", "location": "", "is_default": False})
        wh2 = rw.json()
        rws = requests.get(f"{BASE_URL}/api/warehouses", headers=H(owner["token"]))
        default_w = next(w for w in rws.json() if w.get("is_default"))
        # create product in default WH
        rp = requests.post(f"{BASE_URL}/api/products", headers=H(owner["token"]),
                           json={"name": "TEST_trans_prod", "sale_price": 10, "cost_price": 4, "stock": 10})
        p = rp.json()
        # try to transfer FROM WH2 (product isn't there) TO default
        r = requests.post(f"{BASE_URL}/api/transfers", headers=H(owner["token"]), json={
            "from_warehouse_id": wh2["id"],
            "to_warehouse_id": default_w["id"],
            "items": [{"product_id": p["id"], "name": p["name"], "qty": 1}]
        })
        assert r.status_code == 400
        assert "ليس في المخزن المصدر" in r.text

    def test_qty_greater_than_stock_400(self, owner):
        rws = requests.get(f"{BASE_URL}/api/warehouses", headers=H(owner["token"]))
        default_w = next(w for w in rws.json() if w.get("is_default"))
        wh2 = next(w for w in rws.json() if w["name"] == "TEST_WH2")
        # find prod
        rp = requests.get(f"{BASE_URL}/api/products", headers=H(owner["token"]))
        p = next(x for x in rp.json() if x["name"] == "TEST_trans_prod")
        r = requests.post(f"{BASE_URL}/api/transfers", headers=H(owner["token"]), json={
            "from_warehouse_id": default_w["id"],
            "to_warehouse_id": wh2["id"],
            "items": [{"product_id": p["id"], "name": p["name"], "qty": p["stock"] + 100}]
        })
        assert r.status_code == 400
        assert "أكبر من الرصيد" in r.text

    def test_valid_transfer_and_twin_creation(self, owner):
        rws = requests.get(f"{BASE_URL}/api/warehouses", headers=H(owner["token"]))
        default_w = next(w for w in rws.json() if w.get("is_default"))
        wh2 = next(w for w in rws.json() if w["name"] == "TEST_WH2")
        rp = requests.get(f"{BASE_URL}/api/products", headers=H(owner["token"]))
        p = next(x for x in rp.json() if x["name"] == "TEST_trans_prod")
        stock_before = p["stock"]

        r = requests.post(f"{BASE_URL}/api/transfers", headers=H(owner["token"]), json={
            "from_warehouse_id": default_w["id"],
            "to_warehouse_id": wh2["id"],
            "items": [{"product_id": p["id"], "name": p["name"], "qty": 3}]
        })
        assert r.status_code == 200, r.text
        t = r.json()
        assert "transfer_no" in t
        assert t["from_warehouse_id"] == default_w["id"]
        assert t["to_warehouse_id"] == wh2["id"]

        # source decremented
        rp2 = requests.get(f"{BASE_URL}/api/products", headers=H(owner["token"]))
        src = next(x for x in rp2.json() if x["id"] == p["id"])
        assert src["stock"] == stock_before - 3

        # twin created in WH2
        twins = [x for x in rp2.json() if x["name"] == p["name"] and x["warehouse_id"] == wh2["id"]]
        assert len(twins) == 1
        assert twins[0]["stock"] == 3
        assert twins[0]["id"] != p["id"]

    def test_second_transfer_increments_existing_twin(self, owner):
        rws = requests.get(f"{BASE_URL}/api/warehouses", headers=H(owner["token"]))
        default_w = next(w for w in rws.json() if w.get("is_default"))
        wh2 = next(w for w in rws.json() if w["name"] == "TEST_WH2")
        rp = requests.get(f"{BASE_URL}/api/products", headers=H(owner["token"]))
        src = next(x for x in rp.json() if x["name"] == "TEST_trans_prod" and x["warehouse_id"] == default_w["id"])

        r = requests.post(f"{BASE_URL}/api/transfers", headers=H(owner["token"]), json={
            "from_warehouse_id": default_w["id"],
            "to_warehouse_id": wh2["id"],
            "items": [{"product_id": src["id"], "name": src["name"], "qty": 2}]
        })
        assert r.status_code == 200, r.text

        rp2 = requests.get(f"{BASE_URL}/api/products", headers=H(owner["token"]))
        twins = [x for x in rp2.json() if x["name"] == "TEST_trans_prod" and x["warehouse_id"] == wh2["id"]]
        assert len(twins) == 1, f"expected 1 twin got {len(twins)}"
        assert twins[0]["stock"] == 5  # 3 + 2

    def test_list_populates_warehouse_names(self, owner):
        r = requests.get(f"{BASE_URL}/api/transfers", headers=H(owner["token"]))
        assert r.status_code == 200
        rows = r.json()
        assert len(rows) >= 2
        for row in rows:
            assert row.get("from_warehouse_name") and row["from_warehouse_name"] != "—"
            assert row.get("to_warehouse_name") and row["to_warehouse_name"] != "—"
            assert "transfer_no" in row
